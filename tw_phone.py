# -*- coding: utf-8 -*-
"""台灣電話:從一行文字抓號碼、轉電話標準形(CONTEXT.md;ADR-0011)。

電話標準形 = 純數字、國內前導 0(+886 還原成 0),如 0919889969、037985657。
O 欄輸出、雇主電話的同號計數、名冊反查都用它 —— 同一支號碼在系統裡只有一種樣子。
不加連字號:區碼長度不一(02、037、0826…),放錯位置反而誤導。

只依賴標準函式庫:employer_extract(抓號碼)與 permit_lookup(名冊反查)都 import 它,
彼此不必互相依賴。
"""
import re

# 台灣電話:0 開頭,號段間可夾 '-'/空白(涵蓋 02-2727-6999 這種雙連字號)。
# 總位數收斂 9~10 碼(台灣市話/手機),排除統編(8碼)、放款金額(如 0075-0010)等雜訊。
_PHONE = re.compile(r"(?<!\d)(0\d(?:[-\s]?\d){7,8})(?!\d)")
# 括號區碼格式:(04)7775-863、(02) 2371-7608。
_PHONE_PAREN = re.compile(r"\((0\d{1,3})\)\s*(\d{3,4})\s*-?\s*(\d{3,4})(?!\d)")
# 國際格式 +886 / 886:國碼後省略市話/手機的前導 0(+886 2 2727 6999 = 0227276999、
# +886 912 345 678 = 0912345678),抓國碼後的數字段(容分隔)。
_PHONE_INTL = re.compile(r"(?<!\d)\+?886[\s.-]*([\d][\d\s.-]{6,12}\d)")

# 台灣市話/手機標準形為 9~10 碼;低於此長度視為殘段(分機、缺區碼的第二支)。
# 同時是前綴反查的最短比對長度——兩處用同一個值,避免各自漂移。
PHONE_MIN_LEN = 8


def standard_form(phone: str) -> str:
    """轉電話標準形:去掉所有非數字(02-2727-6999 → 0227276999)。
    國際格式 +886(去非數字後為 886…)還原為國內前導 0:886227276999 → 0227276999。
    國內號一律 0 開頭、無 886 前綴,故此轉換只會命中國際格式,不誤傷國內號。"""
    n = re.sub(r"\D", "", str(phone or ""))
    if n.startswith("886"):
        n = "0" + n[3:].lstrip("0")   # 去國碼、還原單一前導 0(容 +886-02… 這種多寫 0)
    return n


def phones_in(line: str) -> list[str]:
    """抓一行內的台灣電話,回電話標準形(去重保序)。

    一般格式、括號區碼、+886 國際格式三條規則各抓一次;同一段字被兩條規則都抓到
    (+886-02-2727-6999)只算一次 —— 呼叫端拿出現次數挑雇主電話,不能被重複抓灌水。"""
    out: list[str] = []

    def add(n: str) -> None:
        if n not in out:
            out.append(n)

    for m in _PHONE.findall(line):
        add(standard_form(m))
    for area, a, b in _PHONE_PAREN.findall(line):
        add(area + a + b)
    for m in _PHONE_INTL.finditer(line):
        digits = re.sub(r"\D", "", m.group(1)).lstrip("0")  # 去 886 後分隔與冗餘前導 0
        if 8 <= len(digits) <= 9:                  # 市話8 / 手機9(皆已省前導 0)
            add("0" + digits)
    return out
