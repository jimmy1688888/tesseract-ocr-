# -*- coding: utf-8 -*-
"""台灣電話:從一行文字抓號碼、轉電話標準形與顯示形(CONTEXT.md;ADR-0011)。

電話標準形 = 純數字、國內前導 0(+886 還原成 0),如 0919889969、037985657。
O 欄輸出、雇主電話的同號計數、名冊反查都用它 —— 同一支號碼在系統裡只有一種樣子。
不加連字號:區碼長度不一(02、037、0826…),放錯位置反而誤導。

只依賴標準函式庫:employer_extract(抓號碼)與 permit_lookup(名冊反查)都 import 它,
彼此不必互相依賴。
"""
import re

# 台灣電話:0 開頭,號段間可夾 '-'/空白(涵蓋 02-2727-6999 這種雙連字號)。
# 總位數收斂 9~10 碼(台灣市話/手機),排除統編(8碼)、放款金額(如 0075-0010)等雜訊。
_PHONE = re.compile(r"(?<!\d)(0\d(?:[-\s]?\d){7,8})(?!\d)")
# 括號區碼格式:(04)7775-863、(02) 2371-7608。
_PHONE_PAREN = re.compile(r"\((0\d{1,3})\)\s*(\d{3,4})\s*-?\s*(\d{3,4})(?!\d)")
# 國際格式 +886 / 886:國碼後省略市話/手機的前導 0(+886 2 2727 6999 = 0227276999、
# +886 912 345 678 = 0912345678),抓國碼後的數字段(容分隔)。
_PHONE_INTL = re.compile(r"(?<!\d)\+?886[\s.-]*([\d][\d\s.-]{6,12}\d)")

# 台灣市話/手機標準形為 9~10 碼;低於此長度視為殘段(分機、缺區碼的第二支)。
# 同時是前綴反查的最短比對長度——兩處用同一個值,避免各自漂移。
PHONE_MIN_LEN = 8


def standard_form(phone: str) -> str:
    """轉電話標準形:去掉所有非數字(02-2727-6999 → 0227276999)。
    國際格式 +886(去非數字後為 886…)還原為國內前導 0:886227276999 → 0227276999。
    國內號一律 0 開頭、無 886 前綴,故此轉換只會命中國際格式,不誤傷國內號。"""
    n = re.sub(r"\D", "", str(phone or ""))
    if n.startswith("886"):
        n = "0" + n[3:].lstrip("0")   # 去國碼、還原單一前導 0(容 +886-02… 這種多寫 0)
    return n


def phones_in(line: str) -> list[str]:
    """抓一行內的台灣電話,回電話標準形(去重保序)。

    一般格式、括號區碼、+886 國際格式三條規則各抓一次;同一段字被兩條規則都抓到
    (+886-02-2727-6999)只算一次 —— 呼叫端拿出現次數挑雇主電話,不能被重複抓灌水。
    代價:同一行真的寫了兩次同一支號碼,也只算一次;「出現兩次」要靠兩行。"""
    out: list[str] = []

    def add(n: str) -> None:
        if n not in out:
            out.append(n)

    for m in _PHONE.findall(line):
        add(standard_form(m))
    for area, a, b in _PHONE_PAREN.findall(line):
        add(standard_form(area + a + b))
    for m in _PHONE_INTL.finditer(line):
        n = standard_form("886" + m.group(1))   # +886 還原只在 standard_form 一處
        if 9 <= len(n) <= 10:                   # 市話 9 / 手機 10(還原前導 0 後)
            add(n)
    return out


# 數位發展部《公眾電信網路號碼計畫》國內有效號碼指配表(2022/8/27 起主管機關由 NCC
# 改為數位部):區碼 → [(市話首碼, 總碼長含字頭 0)]。同一區碼依首碼分給不同縣市,
# 碼長可能不同(04:臺中首碼 2、3 為 10 碼,彰化首碼 7、8 為 9 碼)。
# 長區碼的前綴在編碼上保留給該區(03 首碼無 7、04 首碼無 9、082 首碼無 6),
# 所以最長前綴比對不會切錯:037985657 必為苗栗 → 037-985657。
_AREA_CODES: dict[str, list[tuple[str, int]]] = {
    "02":   [("235678", 10)],                  # 臺北市、新北市、基隆市
    "03":   [("234", 9), ("56", 9),            # 桃園市、新竹縣市
             ("8", 9), ("9", 9)],              # 花蓮縣、宜蘭縣
    "037":  [("23456789", 9)],                 # 苗栗縣
    "04":   [("23", 10), ("78", 9)],           # 臺中市、彰化縣
    "049":  [("23456789", 10)],                # 南投縣
    "05":   [("234", 9), ("567", 9)],          # 嘉義縣市、雲林縣
    "06":   [("23567", 9), ("9", 9)],          # 臺南市、澎湖縣
    "07":   [("23456789", 9)],                 # 高雄市
    "08":   [("478", 9)],                      # 屏東縣
    "082":  [("2345789", 9)],                  # 金門
    "0826": [("6", 9)],                        # 烏坵
    "0836": [("23456789", 9)],                 # 馬祖
    "089":  [("23456789", 9)],                 # 臺東縣
}
_AREA_LONGEST_FIRST = sorted(_AREA_CODES, key=len, reverse=True)
# 行動通信:085、086、090~098,總碼長 10 碼。
_MOBILE_PREFIXES = ("085", "086", *(f"09{d}" for d in "012345678"))


def display_form(phone: str) -> str:
    """電話顯示形(CONTEXT.md):給人讀的 O 欄寫法,由電話標準形推得,不拿來比對。

    手機 4-3-3(0920-875-667);市話只在區碼後加一個連字號(02-27276999、037-985657),
    不替號碼本體分組 —— 7 碼斷 3-4 還是 4-3,台灣沒有統一慣例。
    不符區碼表(開頭不在表上、首碼或長度與該區不合)→ 退回標準形:純數字本身就是訊號。"""
    n = standard_form(phone)
    if len(n) == 10 and n.startswith(_MOBILE_PREFIXES):
        return f"{n[:4]}-{n[4:7]}-{n[7:]}"
    area = next((a for a in _AREA_LONGEST_FIRST if n.startswith(a)), None)
    if area is None or len(n) == len(area):
        return n
    first = n[len(area)]
    if any(first in heads and len(n) == total for heads, total in _AREA_CODES[area]):
        return f"{area}-{n[len(area):]}"
    return n
